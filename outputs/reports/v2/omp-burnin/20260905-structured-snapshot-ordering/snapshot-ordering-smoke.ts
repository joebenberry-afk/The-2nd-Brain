import {AsyncJobManager} from "./pinned-job-manager";
const gate=Promise.withResolvers<void>();
const entered=Promise.withResolvers<void>();
const manager=new AsyncJobManager({});
manager.registerDeliverySink("owner",async()=>{entered.resolve();await gate.promise;});
const id=manager.register("task","retained delivery",async()=>"result",{ownerId:"owner",agentId:"worker"});
await entered.promise;
const before=manager.getRecentJobs(5,{ownerId:"owner"});
assert.equal(before.find(j=>j.id===id)?.status,"completed");
await Bun.sleep(300100);
const after=manager.getRecentJobs(5,{ownerId:"owner"});
assert.equal(after.find(j=>j.id===id),undefined);
assert.ok(manager.getDeliveryState({ownerId:"owner"}).pendingJobIds.includes(id));
